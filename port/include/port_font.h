static inline void font_draw_char(uint8_t *buf, int x, int y, char c, uint8_t fg) {
    if (!buf || x < 0 || x + 8 > SCREEN_W || y < 0 || y + 8 > SCREEN_H) return;
    if (c == ' ') return;
    if (c < FONT_FIRST_CHAR || c > FONT_LAST_CHAR) c = '?';
    const uint8_t *glyph = g_font_data[(uint8_t)c - (uint8_t)FONT_FIRST_CHAR];
    for (int row = 0; row < 8; row++) {
        uint8_t mask = glyph[row];
        uint8_t *dst = buf + (y + row) * SCREEN_W + x;
        for (int col = 0; col < 8; col++) {
            if (mask & (0x80 >> col)) {
                dst[col] = fg;
            }
        }
    }
}

static inline void font_draw_text(uint8_t *buf, int x, int y, const char *str, uint8_t fg) {
    if (!buf || !str) return;
    int cur_x = x;
    while (*str) {
        if (*str == '\n') {
            cur_x = x;
            y += 10;
        } else {
            font_draw_char(buf, cur_x, y, *str, fg);
            cur_x += 8;
        }
        str++;
    }
}

static inline void font_draw_text_shadow(uint8_t *buf, int x, int y, const char *str, uint8_t fg, uint8_t shadow) {
    font_draw_text(buf, x + 1, y + 1, str, shadow);
    font_draw_text(buf, x, y, str, fg);
}

static inline void font_draw_text_centered(uint8_t *buf, int y, const char *str, uint8_t fg) {
    if (!buf || !str) return;
    int len = (int)strlen(str);
    int x = (SCREEN_W - len * 8) / 2;
    if (x < 0) x = 0;
    font_draw_text(buf, x, y, str, fg);
}

static inline void font_draw_text_centered_shadow(uint8_t *buf, int y, const char *str, uint8_t fg, uint8_t shadow) {
    if (!buf || !str) return;
    int len = (int)strlen(str);
    int x = (SCREEN_W - len * 8) / 2;
    if (x < 0) x = 0;
    font_draw_text_shadow(buf, x, y, str, fg, shadow);
}

static inline int font_draw_text_wrapped(uint8_t *buf, int x, int y, int max_chars, const char *str, uint8_t fg, int max_lines) {
    if (!buf || !str) return 0;
    int line = 0;
    const char *p = str;
    while (*p && line < max_lines) {
        while (*p == ' ') p++;
        if (!*p) break;
        int len = 0;
        int last_space = -1;
        while (p[len] && len < max_chars && p[len] != '\n') {
            if (p[len] == ' ') last_space = len;
            len++;
        }
        int take = len;
        if (p[len] != '\0' && p[len] != '\n' && last_space > 0) {
            take = last_space;
        }
        char line_buf[128];
        if (take >= 127) take = 127;
        memcpy(line_buf, p, take);
        line_buf[take] = '\0';
        font_draw_text(buf, x, y + line * 9, line_buf, fg);
        line++;
        p += take;
        if (*p == '\n' || *p == ' ') p++;
    }
    return line;
}

static inline void font_draw_rect(uint8_t *buf, int x, int y, int w, int h, uint8_t color) {
    if (!buf) return;
    for (int r = y; r < y + h && r < SCREEN_H; r++) {
        if (r < 0) continue;
        for (int c = x; c < x + w && c < SCREEN_W; c++) {
            if (c < 0) continue;
            buf[r * SCREEN_W + c] = color;
        }
    }
}

static inline void font_draw_box(uint8_t *buf, int x, int y, int w, int h, uint8_t border, uint8_t fill) {
    font_draw_rect(buf, x, y, w, h, fill);
    for (int c = x; c < x + w && c < SCREEN_W; c++) {
        if (y >= 0 && y < SCREEN_H) buf[y * SCREEN_W + c] = border;
        if (y + h - 1 >= 0 && y + h - 1 < SCREEN_H) buf[(y + h - 1) * SCREEN_W + c] = border;
    }
    for (int r = y; r < y + h && r < SCREEN_H; r++) {
        if (x >= 0 && x < SCREEN_W) buf[r * SCREEN_W + x] = border;
        if (x + w - 1 >= 0 && x + w - 1 < SCREEN_W) buf[r * SCREEN_W + (x + w - 1)] = border;
    }
}

